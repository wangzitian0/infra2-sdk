"""Environment-provided application settings contracts.

Contract version 2 adds the *source class* of every field: who may legitimately produce
its value. Everything a deployment derives from the manifest (secret-store paths, agent
templates, policies, reconciliation) keys off ``EnvironmentField.source``.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
from collections.abc import Mapping
from dataclasses import asdict, dataclass, replace
from enum import StrEnum
from pathlib import Path
from typing import Any, get_args

from infra2_sdk._wire import (
    canonical_sha256 as _canonical_sha256,
)
from infra2_sdk._wire import (
    parse_contract_version,
    parse_string,
    require_contract_version,
)
from infra2_sdk.runtime.environment import EnvironmentConflictError

_ENVIRONMENT_MANIFEST_VERSION = 2


class _FieldSource(StrEnum):
    """Who produces a value. Exactly one class per field."""

    BOOTSTRAP = "bootstrap"  # provisioning credentials; never reaches an application
    HUMAN = "human"  # issued outside the system, entered once into the human store
    RUNTIME = "runtime"  # generated by the deployment, lives only in the secret store
    RELEASE = "release"  # derived from the release request (tag, sha, digest)
    DECISION = "decision"  # a reviewed human decision recorded in the app repository
    CODE = "code"  # a default in the settings model, never stored


_STORE_BACKED_SOURCES = frozenset({_FieldSource.HUMAN, _FieldSource.RUNTIME})
_COMPOSE_SOURCES = frozenset({_FieldSource.RELEASE, _FieldSource.DECISION})
_FIELD_SCOPES = ("env", "project")
_CI_POLICIES = ("forbidden", "allowed")
_PROVIDED_BY_RE = re.compile(r"\A[a-z][a-z0-9_]*/[a-z][a-z0-9_-]*:[A-Za-z_][A-Za-z0-9_]*\Z")
_PLACEHOLDER_RE = re.compile(r"\{([A-Za-z_][A-Za-z0-9_]*)\}")
_ENV_PLACEHOLDER_RE = re.compile(r"\{env:([A-Z][A-Z0-9_]*)\}")


@dataclass(frozen=True)
class EnvironmentField:
    """One environment variable exposed by an application settings model."""

    field: str
    env: str
    aliases: tuple[str, ...] = ()
    required: bool = False
    injected: bool = False
    has_default: bool = True
    sensitive: bool = False
    group: str = "Application"
    description: str = ""
    source: str = _FieldSource.CODE
    empty_ok: bool = False
    scope: str = "env"
    provided_by: str = ""
    composed_from: str = ""
    mirror_to_1password: bool = False
    ci: str = "forbidden"
    store_key: str = ""

    def __post_init__(self) -> None:
        if not self.field or not self.env:
            raise ValueError("field and env must be non-empty")
        names = (self.env, *self.aliases)
        if len(names) != len(set(names)):
            raise ValueError(f"duplicate environment alias for {self.field}")
        if self.source not in set(_FieldSource):
            raise ValueError(f"{self.field}: unknown source {self.source!r}")
        object.__setattr__(self, "source", str(_FieldSource(self.source)))
        if self.scope not in _FIELD_SCOPES:
            raise ValueError(f"{self.field}: scope must be one of {_FIELD_SCOPES}")
        if self.ci not in _CI_POLICIES:
            raise ValueError(f"{self.field}: ci must be one of {_CI_POLICIES}")
        if self.provided_by and not _PROVIDED_BY_RE.match(self.provided_by):
            raise ValueError(f"{self.field}: provided_by must look like project/service:KEY")
        if self.mirror_to_1password and self.source != _FieldSource.RUNTIME:
            raise ValueError(f"{self.field}: only runtime fields can mirror to 1Password")
        if self.required and self.empty_ok:
            raise ValueError(f"{self.field}: a required field cannot be empty_ok")
        if self.store_key and not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", self.store_key):
            raise ValueError(f"{self.field}: store_key must be an identifier")
        if self.composed_from and not (
            _PLACEHOLDER_RE.search(self.composed_from)
            or _ENV_PLACEHOLDER_RE.search(self.composed_from)
        ):
            raise ValueError(
                f"{self.field}: composed_from needs a {{KEY}} or {{env:NAME}} placeholder"
            )

    @property
    def key(self) -> str:
        """Name of the value in the secret store (defaults to the environment name)."""
        return self.store_key or self.env

    @property
    def store_backed(self) -> bool:
        """True when the value lives in the deployment secret store under this service."""
        return self.source in _STORE_BACKED_SOURCES and not self.provided_by

    @property
    def composed_keys(self) -> tuple[str, ...]:
        """Store keys referenced by ``composed_from`` (``{KEY}``)."""
        return tuple(dict.fromkeys(_PLACEHOLDER_RE.findall(self.composed_from)))

    @property
    def composed_env(self) -> tuple[str, ...]:
        """Host environment names referenced by ``composed_from`` (``{env:NAME}``)."""
        return tuple(dict.fromkeys(_ENV_PLACEHOLDER_RE.findall(self.composed_from)))

    @property
    def rendered(self) -> bool:
        """True when the Vault Agent template carries this field."""
        return self.store_backed or bool(self.provided_by) or bool(self.composed_from)

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        data["aliases"] = list(self.aliases)
        return data

    @classmethod
    def from_dict(cls, raw: Mapping[str, Any]) -> EnvironmentField:
        aliases = raw.get("aliases", [])
        if not isinstance(aliases, list) or any(not isinstance(value, str) for value in aliases):
            raise ValueError("aliases must be an array of strings")
        return cls(
            field=parse_string(raw, "field"),
            env=parse_string(raw, "env"),
            aliases=tuple(aliases),
            required=_boolean(raw, "required"),
            injected=_boolean(raw, "injected"),
            has_default=_boolean(raw, "has_default", default=True),
            sensitive=_boolean(raw, "sensitive"),
            group=parse_string(raw, "group", required=False) or "Application",
            description=parse_string(raw, "description", required=False),
            source=parse_string(raw, "source", required=False) or _FieldSource.CODE,
            empty_ok=_boolean(raw, "empty_ok"),
            scope=parse_string(raw, "scope", required=False) or "env",
            provided_by=parse_string(raw, "provided_by", required=False),
            composed_from=parse_string(raw, "composed_from", required=False),
            mirror_to_1password=_boolean(raw, "mirror_to_1password"),
            ci=parse_string(raw, "ci", required=False) or "forbidden",
            store_key=parse_string(raw, "store_key", required=False),
        )


@dataclass(frozen=True)
class EnvironmentManifest:
    """Versioned application configuration contract for any environment producer."""

    source: str
    fields: tuple[EnvironmentField, ...]
    contract_version: int = _ENVIRONMENT_MANIFEST_VERSION

    def __post_init__(self) -> None:
        require_contract_version(
            self.contract_version,
            _ENVIRONMENT_MANIFEST_VERSION,
            description="environment manifest version",
        )
        if not self.source:
            raise ValueError("source is required")
        owners: dict[str, str] = {}
        for field in self.fields:
            for env_name in (field.env, *field.aliases):
                owner = owners.get(env_name)
                if owner is not None:
                    raise ValueError(
                        f"environment variable {env_name!r} is shared by {owner!r} "
                        f"and {field.field!r}"
                    )
                owners[env_name] = field.field

    def by_source(self, *sources: _FieldSource | str) -> tuple[EnvironmentField, ...]:
        wanted = {str(_FieldSource(source)) for source in sources}
        return tuple(field for field in self.fields if field.source in wanted)

    @property
    def store_backed(self) -> tuple[EnvironmentField, ...]:
        return tuple(field for field in self.fields if field.store_backed)

    def to_dict(self) -> dict[str, Any]:
        return {
            "contract_version": self.contract_version,
            "source": self.source,
            "fields": [field.to_dict() for field in self.fields],
        }

    @classmethod
    def from_dict(cls, raw: Mapping[str, Any]) -> EnvironmentManifest:
        contract_version = parse_contract_version(
            raw,
            _ENVIRONMENT_MANIFEST_VERSION,
            description="environment manifest version",
        )
        fields = raw.get("fields")
        if not isinstance(fields, list) or any(not isinstance(value, Mapping) for value in fields):
            raise ValueError("fields must be an array of objects")
        return cls(
            contract_version=contract_version,
            source=parse_string(raw, "source"),
            fields=tuple(EnvironmentField.from_dict(value) for value in fields),
        )

    def validate_offline(self) -> list[str]:
        """Return contract violations in this manifest without external infrastructure."""
        errors: list[str] = []
        declared = {field.env for field in self.fields}
        for field in self.fields:
            name = field.env
            settled = field.empty_ok or field.required or field.injected
            if field.store_backed and field.has_default and not settled:
                errors.append(
                    f"{name}: {field.source} value must be required, injected or empty_ok"
                )
            if field.source in _COMPOSE_SOURCES and not field.injected:
                errors.append(f"{name}: {field.source} value must be injected by the deployment")
            if field.sensitive and field.source == _FieldSource.CODE and not field.provided_by:
                errors.append(f"{name}: a sensitive value cannot be a code default")
            if field.source == _FieldSource.BOOTSTRAP:
                errors.append(f"{name}: bootstrap values never enter an application manifest")
            for key in field.composed_keys:
                provider_key = field.provided_by.split(":", 1)[1] if field.provided_by else ""
                if key not in declared and key != provider_key:
                    errors.append(f"{name}: composed_from references undeclared {key}")
        return errors


@dataclass(frozen=True)
class _EnvironmentValidation:
    missing: tuple[str, ...]
    resolved: Mapping[str, str]

    @property
    def valid(self) -> bool:
        return not self.missing


def environment_manifest_from_model(
    model: type,
    *,
    source: str | None = None,
    legacy_vault_metadata: bool = True,
    overrides: Mapping[str, Mapping[str, object]] | None = None,
) -> EnvironmentManifest:
    """Extract a manifest; ``vault`` metadata is a temporary v0.2 compatibility alias.

    Source classes and the other supply-chain attributes are read from each field's
    ``json_schema_extra`` (``source``, ``empty_ok``, ``scope``, ``provided_by``,
    ``composed_from``, ``mirror_to_1password``, ``ci``). Release and decision fields are
    always ``injected``: the deployment, not the secret store, supplies them.

    ``overrides`` is a side table keyed by *field name* (not env name) carrying the same
    attributes, for models whose ``Field()`` signatures must not change (a public-API
    compatibility gate); a name that is not a model field is an error, and a release or
    decision override implies ``injected`` exactly as an inline declaration does.
    """

    model_fields = getattr(model, "model_fields", None)
    if not isinstance(model_fields, Mapping):
        raise TypeError("model must expose Pydantic v2 model_fields")
    model_config = getattr(model, "model_config", {})
    env_prefix = model_config.get("env_prefix", "") if isinstance(model_config, Mapping) else ""
    if not isinstance(env_prefix, str):
        env_prefix = ""
    fields: list[EnvironmentField] = []
    for name, info in model_fields.items():
        validation_aliases = list(_validation_aliases(getattr(info, "validation_alias", None)))
        canonical = (
            validation_aliases[0]
            if validation_aliases
            else f"{env_prefix}{getattr(info, 'alias', None) or name}".upper()
        )
        aliases = validation_aliases[1:]
        extra = getattr(info, "json_schema_extra", None) or {}
        if not isinstance(extra, Mapping):
            extra = {}
        annotation = getattr(info, "annotation", None)
        extra_keys = extra.get("extra_keys", ())
        if not isinstance(extra_keys, (list, tuple, set, frozenset)):
            extra_keys = ()
        for extra_key in extra_keys:
            if isinstance(extra_key, str) and extra_key not in aliases:
                aliases.append(extra_key)
        field_source = str(extra.get("source") or _FieldSource.CODE)
        injected = bool(
            extra.get("injected")
            or (legacy_vault_metadata and extra.get("vault"))
            or field_source in _COMPOSE_SOURCES
        )
        # v1 treated every injected value as sensitive because "injected" meant "from
        # Vault". Under v2 the source class says where a value comes from and the legacy
        # ``vault`` alias means only "the deployment injects this"; sensitivity is its own
        # declaration or a Secret type.
        sensitive = bool(extra.get("sensitive")) or _is_secret(annotation)
        is_required = getattr(info, "is_required", None)
        required = bool(is_required()) if callable(is_required) else False
        fields.append(
            EnvironmentField(
                field=str(name),
                env=str(canonical),
                aliases=tuple(alias for alias in aliases if alias != canonical),
                required=required,
                injected=injected,
                has_default=not required,
                sensitive=sensitive,
                group=str(extra.get("group", "Application")),
                description=str(getattr(info, "description", None) or ""),
                source=field_source,
                empty_ok=bool(extra.get("empty_ok", False)),
                scope=str(extra.get("scope") or "env"),
                provided_by=str(extra.get("provided_by") or ""),
                composed_from=str(extra.get("composed_from") or ""),
                mirror_to_1password=bool(extra.get("mirror_to_1password", False)),
                ci=str(extra.get("ci") or "forbidden"),
                store_key=str(extra.get("store_key") or ""),
            )
        )
    if overrides:
        by_name = {field.field: index for index, field in enumerate(fields)}
        unknown = sorted(set(overrides) - set(by_name))
        if unknown:
            raise ValueError(f"overrides name unknown settings fields: {unknown}")
        for name, override in overrides.items():
            changes = dict(override)
            if str(changes.get("source", "")) in _COMPOSE_SOURCES:
                changes.setdefault("injected", True)
            fields[by_name[name]] = replace(fields[by_name[name]], **changes)
    resolved_source = source or f"{model.__module__}.{model.__qualname__}"
    return EnvironmentManifest(source=resolved_source, fields=tuple(fields))


def validate_environment(
    manifest: EnvironmentManifest,
    environ: Mapping[str, str],
    *,
    require_injected: bool = False,
) -> _EnvironmentValidation:
    """Resolve canonical names and aliases without exposing secret values."""

    missing: list[str] = []
    resolved: dict[str, str] = {}
    for field in manifest.fields:
        present: list[tuple[str, str]] = []
        for candidate in (field.env, *field.aliases):
            value = environ.get(candidate)
            if isinstance(value, str) and value.strip():
                present.append((candidate, value if field.sensitive else value.strip()))
        if len({value for _, value in present}) > 1:
            names = ", ".join(name for name, _ in present)
            raise EnvironmentConflictError(
                f"conflicting environment variables for {field.env}: {names}"
            )
        if present:
            resolved[field.env] = present[0][0]
        elif field.required or (require_injected and field.injected):
            missing.append(field.env)
    return _EnvironmentValidation(tuple(sorted(missing)), resolved)


def _load_manifest(path: str | Path, *, root: Path | None = None) -> EnvironmentManifest:
    target = Path(path) if root is None else root / path
    return EnvironmentManifest.from_dict(json.loads(target.read_text(encoding="utf-8")))


def _validate_env(
    manifest: EnvironmentManifest | str | Path,
    environ: Mapping[str, str] | None = None,
    *,
    root: Path | None = None,
    require_injected: bool = True,
) -> list[str]:
    """Names the environment lacks (never values); empty when the process may boot."""
    loaded = (
        manifest
        if isinstance(manifest, EnvironmentManifest)
        else _load_manifest(manifest, root=root)
    )
    env = os.environ if environ is None else environ
    return list(validate_environment(loaded, env, require_injected=require_injected).missing)


def assert_environment(
    manifest_path: str | Path,
    *,
    environ: Mapping[str, str] | None = None,
    require_injected: bool,
) -> None:
    """Raise RuntimeError naming every variable ``manifest_path`` declares and ``environ`` lacks."""
    path = Path(manifest_path)
    if not path.is_file():
        raise RuntimeError(
            f"environment manifest {path} is not in the image; boot validation cannot run (#759)"
        )
    missing = _validate_env(path, environ, require_injected=require_injected)
    if missing:
        raise RuntimeError(
            f"environment lacks {len(missing)} value(s) {path} declares: {', '.join(missing)} "
            f"-- names only; the deployment must inject them (#759)"
        )


def manifest_config_fingerprint(manifest: EnvironmentManifest, values: Mapping[str, str]) -> str:
    """Stable sha256 over the manifest's fields present in ``values``.

    Each value is hashed on its own before the outer digest, so the fingerprint input can
    be logged without leaking a secret. Replaces a store-held ``CONFIGURATION_SHA256``.
    """

    lines = [
        f"{field.env}={hashlib.sha256(values[field.env].encode('utf-8')).hexdigest()}"
        for field in sorted(manifest.fields, key=lambda item: item.env)
        if field.env in values
    ]
    return _canonical_sha256(lines)


def _validation_aliases(alias: Any) -> tuple[str, ...]:
    if isinstance(alias, str):
        return (alias,)
    choices = getattr(alias, "choices", ())
    return tuple(str(choice) for choice in choices if isinstance(choice, str))


def _is_secret(annotation: Any) -> bool:
    if annotation is None:
        return False
    name = getattr(annotation, "__name__", "")
    if isinstance(name, str) and "secret" in name.lower():
        return True
    args = get_args(annotation)
    if args:
        return any(_is_secret(arg) for arg in args)
    return False


def _boolean(raw: Mapping[str, Any], key: str, *, default: bool = False) -> bool:
    value = raw.get(key, default)
    if not isinstance(value, bool):
        raise ValueError(f"{key} must be a boolean")
    return value


