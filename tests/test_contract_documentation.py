"""Tests ensuring README.md contract documentation strictly matches code SSOT."""

from __future__ import annotations

import difflib
import importlib
import importlib.util
import re
import subprocess
import sys
from pathlib import Path

import pytest

from infra2_sdk.runtime.environment import runtime_env_contract

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
RENDERER = ROOT / "scripts" / "render_env_contract.py"

BEGIN_MARKER = (
    b"<!-- env-contract:begin (generated by scripts/render_env_contract.py; do not edit) -->"
)
END_MARKER = b"<!-- env-contract:end -->"


def _load_renderer():
    spec = importlib.util.spec_from_file_location("render_env_contract", RENDERER)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _run_renderer(cwd: Path) -> bytes:
    """Run the script the way a developer runs it, from any working directory."""
    result = subprocess.run(
        [sys.executable, str(RENDERER)], cwd=cwd, capture_output=True, check=False, timeout=60
    )
    assert result.returncode == 0, result.stderr.decode("utf-8", "replace")
    return result.stdout


def _readme_block(content: bytes) -> bytes:
    """Bytes between the end of the begin-marker line and the start of the end-marker."""
    assert content.count(BEGIN_MARKER) == 1, "README needs exactly one env-contract begin marker"
    assert content.count(END_MARKER) == 1, "README needs exactly one env-contract end marker"
    start = content.index(BEGIN_MARKER) + len(BEGIN_MARKER)
    assert content[start : start + 1] == b"\n", "the begin marker must end its line"
    start += 1
    stop = content.index(END_MARKER)
    assert start <= stop, "the end marker must come after the begin marker"
    return content[start:stop]


TABLE_HEADER = "| Canonical name | Compatibility aliases | Sensitive |"
TABLE_SEPARATOR = "|---|---|---|"


def _table_problems(block: str, variable_count: int) -> list[str]:
    """Reasons why the text is not the table of a contract with that many variables."""
    problems = []
    lines = block.splitlines()
    if lines[:2] != [TABLE_HEADER, TABLE_SEPARATOR]:
        problems.append("the block does not start with the header and separator rows")
    rows = lines[2:]
    if variable_count < 1:
        problems.append("the contract lists no variable")
    if len(rows) != variable_count:
        problems.append(f"the block has {len(rows)} rows for {variable_count} variables")
    problems += [f"not a table row: {line!r}" for line in lines if line.strip() and line[0] != "|"]
    return problems


def _fence_problems(content: str, begin_marker: str) -> list[str]:
    """Reasons why the block that starts at the marker sits inside a code fence."""
    before = content[: content.index(begin_marker)]
    fences = [line for line in before.splitlines() if line.lstrip().startswith(("```", "~~~"))]
    return ["the block sits inside a code fence"] if len(fences) % 2 else []


def test_readme_environment_block_is_a_table_with_one_row_per_variable() -> None:
    block = _readme_block(README.read_bytes()).decode("utf-8")
    variables = runtime_env_contract()["variables"]
    assert _table_problems(block, len(variables)) == []


def test_readme_environment_block_is_outside_every_code_fence() -> None:
    content = README.read_text(encoding="utf-8")
    assert _fence_problems(content, BEGIN_MARKER.decode("utf-8")) == []


def test_the_table_and_fence_checks_reject_empty_and_wrong_input() -> None:
    good = f"{TABLE_HEADER}\n{TABLE_SEPARATOR}\n| `A_NAME` | none | no |\n"
    assert _table_problems(good, 1) == []
    assert _table_problems("", 1)  # an empty block
    assert _table_problems(f"{TABLE_HEADER}\n{TABLE_SEPARATOR}\n", 1)  # no row
    assert _table_problems(good, 2)  # one row short
    assert _table_problems("", 0)  # an empty contract must not pass either
    assert _table_problems(good + "text outside the table\n", 2)
    marker = "<!-- begin -->"
    assert _fence_problems(f"intro\n{marker}\nrow\n", marker) == []
    assert _fence_problems(f"```text\n{marker}\nrow\n```\n", marker)
    assert _fence_problems(f"~~~\n{marker}\n", marker)
    assert _fence_problems(f"```text\ncode\n```\n{marker}\n", marker) == []


def test_main_prints_exactly_what_render_returns(
    capsysbinary: pytest.CaptureFixture[bytes],
) -> None:
    renderer = _load_renderer()
    assert renderer.main() == 0
    printed = capsysbinary.readouterr().out
    assert printed, "main() printed nothing"
    assert printed == renderer.render(runtime_env_contract()).encode("utf-8")


def test_readme_environment_block_equals_the_renderer_output_byte_for_byte(tmp_path: Path) -> None:
    expected = _run_renderer(tmp_path)
    actual = _readme_block(README.read_bytes())
    if actual != expected:
        diff = "\n".join(
            difflib.unified_diff(
                actual.decode("utf-8", "replace").splitlines(),
                expected.decode("utf-8", "replace").splitlines(),
                "README.md block",
                "scripts/render_env_contract.py",
                lineterm="",
            )
        )
        pytest.fail(
            "The README environment block is stale. Replace the text between the env-contract "
            "markers with the output of `python scripts/render_env_contract.py`.\n" + diff
        )


def test_renderer_output_is_deterministic(tmp_path: Path) -> None:
    assert _run_renderer(tmp_path) == _run_renderer(tmp_path)


def test_renderer_prints_one_row_per_contract_variable_in_contract_order() -> None:
    contract = runtime_env_contract()
    lines = _load_renderer().render(contract).splitlines()
    assert lines[0] == "| Canonical name | Compatibility aliases | Sensitive |"
    assert lines[1] == "|---|---|---|"
    rows = [[cell.strip() for cell in line.split("|")[1:-1]] for line in lines[2:]]
    variables = contract["variables"]
    assert variables, "the contract lists no variable: this test would check nothing"
    assert len(rows) == len(variables)
    for row, variable in zip(rows, variables, strict=True):
        aliases = ", ".join(f"`{alias}`" for alias in variable["aliases"]) or "none"
        assert row == [f"`{variable['name']}`", aliases, "yes" if variable["sensitive"] else "no"]


def test_renderer_marks_aliases_and_sensitive_variables_of_a_synthetic_contract() -> None:
    # No variable of the real contract is sensitive, so the "yes" branch needs its own input.
    contract = {
        "contract_version": 2,
        "variables": [
            {"name": "B_SECRET", "aliases": ["B_OLD", "B_LEGACY"], "sensitive": True},
            {"name": "A_PLAIN", "aliases": [], "sensitive": False},
        ],
    }
    assert _load_renderer().render(contract) == (
        "| Canonical name | Compatibility aliases | Sensitive |\n"
        "|---|---|---|\n"
        "| `B_SECRET` | `B_OLD`, `B_LEGACY` | yes |\n"
        "| `A_PLAIN` | none | no |\n"
    )


@pytest.mark.parametrize("version", [1, 3, True, "2"])
def test_renderer_rejects_an_unsupported_contract_version(version: object) -> None:
    with pytest.raises(ValueError, match="contract version 2"):
        _load_renderer().render({"contract_version": version, "variables": []})


def test_readme_block_extraction_fails_when_a_marker_is_missing() -> None:
    complete = BEGIN_MARKER + b"\nrow\n" + END_MARKER + b"\n"
    assert _readme_block(complete) == b"row\n"
    with pytest.raises(AssertionError, match="begin marker"):
        _readme_block(complete.replace(BEGIN_MARKER, b""))
    with pytest.raises(AssertionError, match="end marker"):
        _readme_block(complete.replace(END_MARKER, b""))


def test_readme_documents_valid_core_runtime_entrypoints() -> None:
    """Verify that all entrypoints documented in README.md Core entrypoints table exist."""
    content = README.read_text(encoding="utf-8")

    pattern = (
        r"### Core runtime entrypoints.*?\n"
        r"\| Capability \| Canonical entrypoint \| Primary module \| Description \|\n"
        r"\|---\|---\|---\|---\|\n"
        r"(.*?)\n\n"
    )
    section_match = re.search(pattern, content, re.DOTALL)
    assert section_match is not None, "Could not find Core runtime entrypoints table in README.md"

    table_body = section_match.group(1).strip()
    checked = 0
    for line in table_body.splitlines():
        cols = [c.strip() for c in line.split("|")[1:-1]]
        assert len(cols) == 4, f"malformed Core runtime entrypoints row: {line!r}"
        _cap, raw_entrypoints, module_name, _desc = cols
        module_name = module_name.strip("` ")
        mod = importlib.import_module(module_name)
        for symbol in re.findall(r"`([A-Za-z0-9_]+)`", raw_entrypoints):
            assert hasattr(mod, symbol), f"Module {module_name!r} does not have symbol {symbol!r}"
            checked += 1
    assert checked, "the Core runtime entrypoints table names no symbol: this test checks nothing"
