"""Positive architecture and package hygiene guards for infra2-sdk v4.10.1."""

from __future__ import annotations

import ast
import importlib
import json
import sys
import tomllib
from pathlib import Path

import infra2_sdk

ROOT = Path(__file__).resolve().parents[1]
SRC_DIR = ROOT / "src" / "infra2_sdk"
EXPECTED_MODULES = ("config", "telemetry", "service", "storage", "llm", "delivery")


def test_package_metadata_and_module_surface() -> None:
    pyproject = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    project = pyproject["project"]
    assert project["version"] == "4.10.1"
    assert infra2_sdk.__all__ == EXPECTED_MODULES

    core_deps = {
        dep.split(">")[0].split("<")[0].split("=")[0].strip() for dep in project["dependencies"]
    }
    assert core_deps == {"pydantic", "pyyaml"}

    public_files = tuple(sorted(p.stem for p in SRC_DIR.glob("*.py") if not p.name.startswith("_")))
    assert set(public_files) == set(EXPECTED_MODULES)
    assert sorted(p.name for p in SRC_DIR.iterdir() if p.is_dir() and p.name != "__pycache__") == [
        "data"
    ]

    for mod_name in EXPECTED_MODULES:
        mod = importlib.import_module(f"infra2_sdk.{mod_name}")
        exports = tuple(mod.__all__)
        assert len(exports) == len(set(exports)), f"duplicate export in {mod_name}"
        for sym in exports:
            assert hasattr(mod, sym), f"{mod_name}.__all__ lists missing symbol {sym!r}"


def test_no_cross_module_private_imports_or_ambiguous_env_reads() -> None:
    for py_path in SRC_DIR.glob("*.py"):
        tree = ast.parse(py_path.read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            if (
                isinstance(node, ast.ImportFrom)
                and node.module
                and node.module.startswith("infra2_sdk.")
            ):
                target_leaf = node.module.split(".", 1)[1]
                allowed_internal = {"_core", "_schema_gate", "_llm_runtime"}
                if target_leaf not in allowed_internal:
                    for alias in node.names:
                        assert not alias.name.startswith("_"), (
                            f"{py_path.name} imports private {alias.name} from {node.module}"
                        )
            if isinstance(node, (ast.Subscript, ast.Call)):
                src_seg = ast.unparse(node)
                assert 'environ.get("ENV"' not in src_seg and "environ['ENV']" not in src_seg


def test_generated_contracts_and_canary_manifest_in_sync() -> None:
    sys.path.insert(0, str(ROOT / "canary" / "todo"))
    try:
        from canary_settings import CanarySettings
    finally:
        sys.path.pop(0)

    manifest = infra2_sdk.config.EnvironmentManifest.from_model(
        CanarySettings, source="canary/todo"
    )
    raw_manifest = json.loads(
        (ROOT / "canary" / "todo" / "env.manifest.json").read_text(encoding="utf-8")
    )
    assert raw_manifest == manifest.to_dict()

    contract_doc = (ROOT / "docs" / "app-integration-contract.md").read_text(encoding="utf-8")
    rendered_script = ROOT / "scripts" / "render_app_contract.py"
    spec = importlib.util.spec_from_file_location("render_app_contract", rendered_script)
    assert spec is not None and spec.loader is not None
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    begin = (
        "<!-- app-contract:begin (generated by scripts/render_app_contract.py; do not edit) -->\n"
    )
    end = "<!-- app-contract:end -->"
    assert begin in contract_doc and end in contract_doc
    actual_slice = contract_doc.split(begin, 1)[1].split(end, 1)[0]
    assert actual_slice == mod.render()
